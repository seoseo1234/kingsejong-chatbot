const words = Object.keys(HARD_WORDS).sort((a, b) => b.length - a.length);
const HARD_WORD_PATTERN = new RegExp(`(${words.join('|')})`, 'g');

/**
 * 문장을 [{ text, word? }] 조각으로 나눈다.
 * 같은 낱말은 처음 나올 때만 풀이를 붙여 화면이 너무 어지럽지 않게 한다.
 */
export function splitHardWords(content) {
  const seen = new Set();
  return content.split(HARD_WORD_PATTERN).filter(Boolean).map((part) => {
    if (!HARD_WORDS[part] || seen.has(part)) return { text: part };
    seen.add(part);
    return { text: part, word: part };
  });
}
